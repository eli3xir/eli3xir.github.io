import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {init,parse} from 'es-module-lexer/minimal';
import {publicRoutes,root} from './browser-support.mjs';
import {routeFor} from '../js/experience/domain.js';
import {featureLoaders} from '../js/experience/route-assets.js';
import {modelLoaders} from '../js/world/models.js';
import {experimentLoaders} from '../js/world/experiments.js';

const output=path.join(root,'js/experience/preload.js');
const normalize=pathname=>pathname.replace(/index\.html$/,'').replace(/\/$/,'')||'/';

export async function buildPreloads(){
 await init();
 const routes=publicRoutes(),graphs=new Map(),paths={};
 const htmlPath=pathname=>path.join(root,pathname.endsWith('/')?pathname+'index.html':pathname);
 const read=pathname=>fs.readFileSync(path.join(root,pathname),'utf8');
 const importMap=file=>JSON.parse(fs.readFileSync(file,'utf8').match(/<script type="importmap">([\s\S]*?)<\/script>/)[1]).imports;
 const maps=routes.map(pathname=>importMap(htmlPath(pathname))),imports=maps[0];
 const resolve=(specifier,owner)=>{
  let target=specifier;
  if(!/^(\/|\.\.?\/)/.test(target)){
   const key=Object.keys(imports).sort((a,b)=>b.length-a.length).find(key=>key===target||key.endsWith('/')&&target.startsWith(key));
   if(!key||maps.some(map=>map[key]!==imports[key]))throw new Error(`Missing or inconsistent import map: ${specifier}`);
   target=imports[key]+target.slice(key.length);
  }
  const url=new URL(target,'https://local.invalid'+owner);
  if(url.origin!=='https://local.invalid'||url.search||url.hash||!fs.existsSync(path.join(root,url.pathname)))throw new Error(`Unsupported module ${specifier} from ${owner}`);
  return url.pathname;
 };
 const records=(source,owner)=>parse(source,owner)[0];
 const dynamicRoots=(source,owner)=>{
  const imports=records(source,owner).filter(record=>record.d>=0);
  if(!imports.length||imports.some(record=>!record.n))throw new Error(`Expected literal dynamic imports in ${owner}`);
  return imports.map(record=>resolve(record.n,owner));
 };
 const closure=roots=>{
  const visited=new Set();
  const visit=url=>{
   if(visited.has(url))return;
   visited.add(url);
   for(const record of records(read(url),url))if(record.d===-1)visit(resolve(record.n,url));
  };
  // Start larger responses first so they do not sit behind many tiny modules
  // when a connection has a limited number of simultaneous requests.
  roots.forEach(visit);return [...visited].sort((a,b)=>fs.statSync(path.join(root,b)).size-fs.statSync(path.join(root,a)).size||a.localeCompare(b));
 };
 const entry='/js/experience/entry.js';
 const common=closure([entry,...dynamicRoots(read(entry),entry)]),commonSet=new Set(common);
 const loaderRoots=(loaders,key,owner)=>Object.hasOwn(loaders,key)?dynamicRoots(`const loader=${loaders[key].toString()}`,owner):[];
 for(const pathname of routes){
  const route=routeFor(pathname),key=route.experiment?route.experimentId:route.id;
  paths[normalize(pathname)]=key;
  if(graphs.has(key))continue;
  const model=route.experiment?loaderRoots(experimentLoaders,key,'/js/world/experiments.js'):loaderRoots(modelLoaders,key,'/js/world/models.js');
  if(!model.length)throw new Error(`Missing scene loader: ${pathname}`);
  const features=loaderRoots(featureLoaders,key,'/js/experience/route-assets.js');
  graphs.set(key,closure([...model,...features]).filter(url=>!commonSet.has(url)));
 }
 const urls=[...new Set([...common,...[...graphs.values()].flat()])].sort(),index=new Map(urls.map((url,i)=>[url,i]));
 const ids=urls=>urls.map(url=>index.get(url));
 const perRoute=Object.fromEntries([...graphs].map(([key,urls])=>[key,ids(urls)]));
 const source=`// Generated by tools/build-module-preloads.mjs. Optional hints; native imports own startup.\n(()=>{\n  if(new URLSearchParams(location.search).has('embedded')||!document.createElement('link').relList.supports?.('modulepreload'))return;\n  const urls=${JSON.stringify(urls)},\n    common=${JSON.stringify(ids(common))},\n    routes=${JSON.stringify(perRoute)},\n    paths=${JSON.stringify(paths)},\n    seen=new Set();\n  globalThis.__preloadExperience=pathname=>{\n    const key=paths[pathname.replace(/index\\.html$/,'').replace(/\\/$/,'')||'/'];\n    if(!Object.hasOwn(routes,key))return;\n    for(const id of [...common,...routes[key]]){\n      if(seen.has(id))continue;\n      seen.add(id);\n      const link=document.createElement('link');link.rel='modulepreload';link.href=urls[id];\n      document.head.append(link);\n    }\n  };\n  globalThis.__preloadExperience(location.pathname);\n})();\n`;
 return{source,common,graphs,paths,urls};
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const result=await buildPreloads();
 if(process.argv.includes('--check')){
  if(!fs.existsSync(output)||fs.readFileSync(output,'utf8')!==result.source)throw new Error('Module hints are stale; run npm run build:preloads');
 }else fs.writeFileSync(output,result.source);
 console.log(`${Object.keys(result.paths).length} routes, ${result.common.length} common modules, ${result.urls.length} modules across all scenes`);
}
